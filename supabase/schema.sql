create table if not exists public.benchmark_scores (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  mode text not null check (mode in ('gpu', 'cpu', 'stability')),
  difficulty text not null,
  score integer not null,
  average_fps integer not null,
  stability integer,
  duration integer not null,
  device jsonb
);

alter table public.benchmark_scores enable row level security;
drop policy if exists "Anyone can read scores" on public.benchmark_scores;
drop policy if exists "Anyone can submit scores" on public.benchmark_scores;
create policy "Anyone can read scores" on public.benchmark_scores for select using (true);
create policy "Anyone can submit scores" on public.benchmark_scores for insert with check (true);
